"""# **Function:**

BMI Calculator
"""

def calculate_bmi(weight, height):

    bmi = weight / (height ** 2)

    return bmi

weight = float(input("Enter your weight (in kg): "))

height = float(input("Enter your height (in meters): "))

result = calculate_bmi(weight, height)

print("Calculated BMI:", round(result, 2))